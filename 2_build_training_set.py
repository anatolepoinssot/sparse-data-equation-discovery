"""
2_build_training_set.py
=======================
Build the training set from the raw sensor data generated by script 1.

What this script does
---------------------
1. Load raw sensor data  (T, phi2)  from  data/raw/sensor_data.npz.
2. Compute D1 and D2 at every sensor location using the known D_g^0 and:
       D_g(x, t; a) = D_g^0(x) + gamma_D_g * ln(T(x, t; a) / T_ref)
3. Assign each sensor to its material region (fuel1, fuel2, cr, ref).
4. Select the 7 observed sensors and build Y in R^(7 x 100 x 200).
5. Save the processed training set to  data/processed/training_set_Y.npz.

Usage
-----
    python 2_build_training_set.py
"""

import os
import sys
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from config import (
    X_GRID, Y_GRID, DOMAIN_SIZE,
    T_REF, GAMMA_D1, GAMMA_D2,
    D1_REF_BY_REGION, D2_REF_BY_REGION,
    SENSOR_INDICES, SENSOR_COORDS_CM,
    N_SENSORS_TOTAL, N_SENSORS_OBS,
    OBS_SENSOR_INDICES,
    N_PARAM, N_TIME, A_VALUES,
    SENSOR_DATA_FILE, DATA_PROC_DIR, RESULTS_DIR, TRAINING_SET_FILE,
)


def assign_region(x_cm, y_cm):
    """Return the material region label for a point (x, y) in cm."""
    if x_cm >= 150.0 or y_cm >= 150.0:
        return "ref"
    cr_boxes = [
        (0, 10, 0, 10), (70, 90, 0, 10),
        (70, 90, 70, 90), (0, 10, 70, 90),
    ]
    for (x0, x1, y0, y1) in cr_boxes:
        if x0 <= x_cm <= x1 and y0 <= y_cm <= y1:
            return "cr"
    if 30.0 <= x_cm <= 110.0 and 30.0 <= y_cm <= 110.0:
        return "fuel1"
    return "fuel2"


def get_D0(x_cm, y_cm):
    """Return (D1_ref, D2_ref) for a given spatial position."""
    region = assign_region(x_cm, y_cm)
    return D1_REF_BY_REGION[region], D2_REF_BY_REGION[region]


def main():
    os.makedirs(DATA_PROC_DIR, exist_ok=True)
    os.makedirs(RESULTS_DIR,   exist_ok=True)

    # 1. Load raw sensor data
    print(f"[2_build_training_set] Loading raw data from: {SENSOR_DATA_FILE}")
    data = np.load(SENSOR_DATA_FILE)

    T_raw    = data["T"]     # shape (200, 100, 20)
    phi2_raw = data["phi2"]  # shape (200, 100, 20)
    a_vals   = data["a"]     # shape (200,)
    t_vals   = data["t"]     # shape (100,)

    print(f"    T shape:    {T_raw.shape}")
    print(f"    phi2 shape: {phi2_raw.shape}")
    print(f"    a range:    [{a_vals.min():.4f}, {a_vals.max():.4f}]")
    print(f"    t range:    [{t_vals.min():.4f}, {t_vals.max():.4f}] s")

    # 2. Compute D1 and D2 at all 20 sensor locations
    print("[2_build_training_set] Computing D1 and D2 at all sensors ...")

    D1_all = np.zeros_like(T_raw)
    D2_all = np.zeros_like(T_raw)
    sensor_regions = []
    D1_refs = np.zeros(N_SENSORS_TOTAL)
    D2_refs = np.zeros(N_SENSORS_TOTAL)

    for s, (x_cm, y_cm) in enumerate(SENSOR_COORDS_CM):
        d1ref, d2ref = get_D0(x_cm, y_cm)
        D1_refs[s] = d1ref
        D2_refs[s] = d2ref
        region = assign_region(x_cm, y_cm)
        sensor_regions.append(region)
        tau = np.log(T_raw[:, :, s] / T_REF)
        D1_all[:, :, s] = d1ref + GAMMA_D1 * tau
        D2_all[:, :, s] = d2ref + GAMMA_D2 * tau

    print(f"    Sensor regions: {sensor_regions}")
    print(f"    D1 range: [{D1_all.min():.4f}, {D1_all.max():.4f}] cm")
    print(f"    D2 range: [{D2_all.min():.4f}, {D2_all.max():.4f}] cm")

    # 3. Build training set Y
    obs_idx = OBS_SENSOR_INDICES
    print(f"\n[2_build_training_set] Observed sensor indices: {obs_idx}")
    for i in obs_idx:
        x, y = SENSOR_COORDS_CM[i]
        print(f"      sensor {i:2d}:  ({x:.1f}, {y:.1f})  region={sensor_regions[i]}")

    phi2_obs = phi2_raw[:, :, obs_idx]
    T_obs    = T_raw[:, :, obs_idx]
    D1_obs   = D1_all[:, :, obs_idx]
    D2_obs   = D2_all[:, :, obs_idx]

    # Y[sensor, time, param]
    Y = phi2_obs.transpose(2, 1, 0)   # (N_SENSORS_OBS, N_TIME, N_PARAM)
    print(f"\n    Y (training set) shape: {Y.shape}")

    # 4. Compute tau at all sensors
    tau_all = np.log(T_raw / T_REF)
    tau_obs = tau_all[:, :, obs_idx]
    print(f"\n    tau range: [{tau_all.min():.4f}, {tau_all.max():.4f}]")

    # 5. Save
    np.savez_compressed(
        TRAINING_SET_FILE,
        Y          = Y,
        T_obs      = T_obs.transpose(2, 1, 0),
        D1_obs     = D1_obs.transpose(2, 1, 0),
        D2_obs     = D2_obs.transpose(2, 1, 0),
        tau_obs    = tau_obs.transpose(2, 1, 0),
        T_all      = T_raw,
        D1_all     = D1_all,
        D2_all     = D2_all,
        tau_all    = tau_all,
        phi2_all   = phi2_raw,
        a_vals     = a_vals,
        t_vals     = t_vals,
        obs_idx    = np.array(obs_idx),
        D1_refs    = D1_refs,
        D2_refs    = D2_refs,
        sensor_regions = np.array(sensor_regions),
    )
    print(f"\n[2_build_training_set] Training set saved to: {TRAINING_SET_FILE}")
    print(f"    File size: {os.path.getsize(TRAINING_SET_FILE)/1e6:.2f} MB")

    # 6. Diagnostic plots
    _plot_diagnostics(Y, tau_obs, D1_obs, D2_obs, t_vals, a_vals, obs_idx)
    print("[2_build_training_set] Done.")


def _plot_diagnostics(Y, tau_obs, D1_obs, D2_obs, t_vals, a_vals, obs_idx):
    """Quick diagnostic plots saved to results/."""
    os.makedirs(RESULTS_DIR, exist_ok=True)

    # Plot 1: phi2 time series at observed sensors
    fig, axes = plt.subplots(2, 4, figsize=(16, 6), sharey=False)
    axes = axes.ravel()
    a_sample_idx = [0, 49, 99, 149, 199]
    colors = plt.cm.viridis(np.linspace(0, 1, len(a_sample_idx)))
    for s in range(min(N_SENSORS_OBS, 7)):
        ax = axes[s]
        for ai, ci in zip(a_sample_idx, colors):
            ax.plot(t_vals, Y[s, :, ai], color=ci, label=f"a={a_vals[ai]:.3f}")
        ax.set_title(f"Sensor {obs_idx[s]} (phi2)", fontsize=9)
        ax.set_xlabel("t [s]")
        ax.set_ylabel("phi2")
        if s == 0:
            ax.legend(fontsize=7, loc="upper right")
    axes[-1].axis("off")
    fig.suptitle("phi2 time series at observed sensors (Y training set)", fontsize=11)
    plt.tight_layout()
    out = os.path.join(RESULTS_DIR, "diag_Y_timeseries.png")
    plt.savefig(out, dpi=120)
    plt.close()
    print(f"    [plot] {out}")

    # Plot 2: D1 and D2 vs tau — should be a perfect line
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 5))
    s = 0
    tau_flat = tau_obs[:, :, s].ravel()
    D1_flat  = D1_obs[:, :, s].ravel()
    D2_flat  = D2_obs[:, :, s].ravel()
    tau_range = np.linspace(tau_flat.min(), tau_flat.max(), 200)
    D1_true = D1_REF_BY_REGION["fuel1"] + GAMMA_D1 * tau_range
    D2_true = D2_REF_BY_REGION["fuel1"] + GAMMA_D2 * tau_range
    ax1.scatter(tau_flat, D1_flat, s=1, alpha=0.3, label="Computed D1")
    ax1.plot(tau_range, D1_true, "r-", lw=2, label=f"True: D1_ref + {GAMMA_D1}*tau")
    ax1.set_xlabel("tau = ln(T / T_ref)")
    ax1.set_ylabel("D1 [cm]")
    ax1.set_title(f"D1 vs tau — sensor {obs_idx[s]}")
    ax1.legend()
    ax2.scatter(tau_flat, D2_flat, s=1, alpha=0.3, color="orange", label="Computed D2")
    ax2.plot(tau_range, D2_true, "r-", lw=2, label=f"True: D2_ref + {GAMMA_D2}*tau")
    ax2.set_xlabel("tau = ln(T / T_ref)")
    ax2.set_ylabel("D2 [cm]")
    ax2.set_title(f"D2 vs tau — sensor {obs_idx[s]}")
    ax2.legend()
    fig.suptitle("Ground truth: D_g = D_g^0 + gamma*ln(T/T_ref)  [to be recovered by SINDy]")
    plt.tight_layout()
    out = os.path.join(RESULTS_DIR, "diag_D_vs_tau.png")
    plt.savefig(out, dpi=120)
    plt.close()
    print(f"    [plot] {out}")


if __name__ == "__main__":
    main()
